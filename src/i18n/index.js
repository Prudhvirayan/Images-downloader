export function makeT(lang) {
  const strings = LANGUAGES[lang]?.strings ?? en
  return function t(key, vars = {}) {
    let s = strings[key] ?? en[key] ?? key
    Object.entries(vars).forEach(([k, v]) => { s = s.replace(`{${k}}`, String(v)) })
    return s
  }
}
